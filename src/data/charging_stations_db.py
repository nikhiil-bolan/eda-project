def search_stations(query="", city="All", status="All", max_price=100.0):
    """Filters charging station records by keyword query, city, status, and price."""
    filtered = STATIONS_DATABASE
    if query:
        q = query.lower()
        filtered = [s for s in filtered if q in s['name'].lower() or q in s['city'].lower() or q in s['address'].lower() or q in s['operator'].lower()]
    if city and city != "All":
        filtered = [s for s in filtered if s['city'].lower() == city.lower()]
    if status and status != "All":
        filtered = [s for s in filtered if s['status'].lower() == status.lower()]
    filtered = [s for s in filtered if s['tariff_inr'] <= max_price]
    return filtered
